                    <p>
                        Perkumpulan Ikatan Nasional Analis Kebijakan, yang selanjutnya disingkat menjadi INAKI, didirikan berdasarkan Akta Notaris Taufik SH Nomor 06 tanggal 13 Februari 2025. Kepanjangan INAKI semula adalah Ikatan Nasional Analis Kebijakan Indonesia. Pada saat pendaftaran ke Kementerian Hukum disarankan untuk mengganti nama perkumpulan. Selanjutnya, terjadi perubahan untuk kepanjangan INAKI menjadi Ikatan Nasional Analis Kebijakan dan dibuatkan Akta Perubahan Nomor 06 Tanggal 21 Mei 2025. Akta pendirian INAKI telah disahkan oleh Menteri Hukum nomor: <strong>AHU-0004107.AH.01.07 Tahun 2025 tanggal 11 Juni 2025</strong>.
